STATUS_PATH = Path("docs/progress/STATUS.md")
BLOCKERS_PATH = Path("docs/progress/BLOCKERS.md")
DEBT_PATH = Path("docs/progress/DEBT.md")
DECISIONS_PATH = Path("docs/progress/DECISIONS.md")
OWNER_QUEUE_PATH = Path("docs/progress/OWNER_QUEUE.md")
LEDGER_PATH = Path("docs/outsourcing/LEDGER.md")

_WP_RE = re.compile(r"^WP-(\d+)\.(\d+)$")
_ENTRY_RE = re.compile(r"^(?P<id>(?:BLK|DEBT|DEC|WO|WP)-.+?)(?=$|\s|\|)")


def wp_sort_key(wp: str) -> tuple[int, int, str]:
    """Sort WP IDs numerically: WP-1.9 before WP-1.10; non-matching names last."""
    match = _WP_RE.match(wp.strip())
    if match is None:
        return (10**9, 10**9, wp)
    return (int(match.group(1)), int(match.group(2)), "")


def _id_sort_key(identifier: str) -> tuple[str, tuple[int, ...]]:
    parts = re.split(r"(\d+)", identifier)
    return (identifier.split("-")[0], tuple(int(p) if p.isdigit() else -1 for p in parts))


def _status_sort_key(record: StatusFragment) -> tuple[tuple[int, int, str], str]:
    return (wp_sort_key(record.fields.get("WP", "")), record.path.name)


def _entry_sort_key(identifier: str) -> tuple[tuple[str, tuple[int, ...]], str]:
    return (_id_sort_key(identifier), identifier)


def _status_cell(record: StatusFragment, on_main: bool) -> str:
    value = record.fields.get("Status", "")
    if on_main and value in {"AUDIT-PASS", "MERGE-READY"}:
        return "MERGED"
    return value


def render_status(records: tuple[StatusFragment, ...], on_main: bool) -> str:
    """Render the status table in the legacy layout."""
    rows: list[str] = []
    for record in sorted(records, key=_status_sort_key):
        fields = record.fields
        branch = fields.get("Branch", "")
        pr = fields.get("PR", "")
        branch_pr = f"{branch}, PR {pr}" if pr and pr != "none" else branch
        row = "| {wp} | {title} | {status} | {branch_pr} | {updated} |".format(
            wp=fields.get("WP", ""),
            title=fields.get("Title", ""),
            status=_status_cell(record, on_main),
            branch_pr=branch_pr,
            updated=fields.get("Updated", ""),
        )
        rows.append(row)
    return GENERATED_LINE + STATUS_HEADER + "\n".join(rows) + ("\n" if rows else "")


def _blocker_sort_key(record: BlockerFragment) -> tuple[tuple[str, tuple[int, ...]], str]:
    return _entry_sort_key(record.fields.get("ID", record.path.stem))


def render_blockers(records: tuple[BlockerFragment, ...], on_main: bool) -> str:
    """Render blocker entries, legacy ones verbatim, new ones in the same layout."""
    entries: list[str] = []
    for record in sorted(records, key=_blocker_sort_key):
        if record.fields.get("Legacy") == "yes":
            entry = record.free_text.rstrip("\n")
            entries.append(entry)
        else:
            entries.append(_render_new_blocker(record))
    return GENERATED_LINE + BLOCKERS_HEADER + "\n\n".join(entries) + ("\n" if entries else "")


def _render_new_blocker(record: BlockerFragment) -> str:
    fields = record.fields
    lines = [
        f"## {fields.get('ID', record.path.stem)} — {fields.get('Title', record.path.stem)}",
        f"STATUS: {fields.get('Status', '')}",
    ]
    raised = fields.get("Raised", "")
    session = fields.get("Session", "")
    meta = f"WP: {fields.get('WP', '')}"
    if raised:
        meta += f"  ·  Raised: {raised}"
    if session:
        meta += f"  ·  Session: {session}"
    lines.append(meta)
    body = record.free_text.strip("\n")
    if body:
        lines += ["", body]
    steps = record.steps
    if steps and "Exact steps" not in body:
        lines += ["", "**Exact steps:**"] + [f"{i}. {step}" for i, step in enumerate(steps, 1)]
    owner_answer = fields.get("Owner answer", "")
    if owner_answer:
        lines += ["", f"**Owner answer:** {owner_answer}"]
    return "\n".join(lines)


def render_debt(records: tuple[DebtFragment, ...], on_main: bool) -> str:
    """Render the debt table in the legacy layout, legacy rows verbatim."""
    rows: list[str] = []
    for record in sorted(records, key=lambda r: _entry_sort_key(r.fields.get("ID", r.path.stem))):
        if record.fields.get("Legacy") == "yes":
            row_line = next(
                (line for line in record.free_text.splitlines() if line.strip().startswith("|")),
                "",
            )
            rows.append(row_line.strip())
        else:
            rows.append(_render_new_debt_row(record))
    return GENERATED_LINE + DEBT_HEADER + "\n".join(rows) + ("\n" if rows else "")


def _render_new_debt_row(record: DebtFragment) -> str:
    fields = record.fields
    status = fields.get("Status", "")
    closed_by = fields.get("Closed by", "")
    if closed_by and status == "CLOSED":
        status_cell = f"CLOSED ({closed_by})"
    else:
        status_cell = status
    cells = [
        fields.get("ID", record.path.stem),
        fields.get("Source", ""),
        fields.get("What", ""),
        fields.get("Risk", ""),
        fields.get("Accepted by", ""),
        fields.get("Target WP", ""),
        status_cell,
    ]
    return "| " + " | ".join(cells) + " |"


def render_decisions(records: tuple[DecisionFragment, ...]) -> str:
    lines = ["# Decision records", ""]
    for record in sorted(records, key=lambda r: _entry_sort_key(r.fields.get("ID", r.path.stem))):
        fields = record.fields
        lines.append(f"## {fields.get('ID', record.path.stem)} — {fields.get('Title', '')}".rstrip(" —"))
        lines.append(f"Status: {fields.get('Status', '')}  ·  WP: {fields.get('WP', '')}  ·  Date: {fields.get('Date', '')}")
        if fields.get("Question"):
            lines += ["", f"Question: {fields['Question']}"]
        if record.options:
            lines += ["", "Options:"] + [f"{i}. {opt}" for i, opt in enumerate(record.options, 1)]
        for label in ("Choice", "Why", "Reversal"):
            if fields.get(label):
                lines += ["", f"{label}: {fields[label]}"]
        body = record.free_text.strip("\n")
        if body:
            lines += ["", body]
        lines.append("")
    return GENERATED_LINE + "\n".join(lines).rstrip("\n") + "\n"


def _unmerged_count(record: BlockerFragment, merged_wps: set[str]) -> int:
    raw = record.fields.get("Unblocks", "")
    count = 0
    for token in re.split(r"[,\s]+", raw):
        token = token.strip()
        if token.startswith("WP-") and token not in merged_wps:
            count += 1
    return count


def _owner_queue_order(
    blockers: tuple[BlockerFragment, ...],
    merged_wps: set[str],
) -> list[BlockerFragment]:
    open_blockers = [b for b in blockers if b.fields.get("Status") != "RESOLVED"]

    def key(record: BlockerFragment) -> tuple[int, str, str]:
        return (-_unmerged_count(record, merged_wps), record.fields.get("Raised", "9999-12-31"), record.fields.get("ID", ""))

    return sorted(open_blockers, key=key)


def render_owner_queue(
    fragments: Fragments,
    on_main: bool,
    last_digest: str | None,
) -> str:
    """Render the owner queue: open blockers, new decisions, pending checks."""
    merged_wps = {
        record.fields.get("WP", "")
        for record in fragments.status
        if _status_cell(record, on_main) == "MERGED"
    }
    lines = ["# Owner queue", ""]
    lines.append("Ordered by how many unmerged WPs each blocker unblocks, then by age.")
    lines.append("")
    lines.append("## Open blockers")
    lines.append("")
    ordered = _owner_queue_order(fragments.blockers, merged_wps)
    if not ordered:
        lines.append("None.")
    for record in ordered:
        fields = record.fields
        lines.append(f"### {fields.get('ID', record.path.stem)}")
        lines.append(f"- Class: {fields.get('Owner capability', '')}")
        lines.append(f"- Time needed: {fields.get('Time needed', '')}")
        lines.append(f"- Unblocks: {fields.get('Unblocks', '')}")
        steps = record.steps
        if not steps:
            steps = tuple(
                re.sub(r"^\d+\.\s*", "", line.strip())
                for line in record.free_text.splitlines()
                if re.match(r"^\d+\.\s", line.strip())
            )
        if steps:
            lines.append("- Exact steps:")
            lines.extend(f"  {i}. {step}" for i, step in enumerate(steps, 1))
        lines.append("")
    lines.append("## Decisions awaiting review")
    lines.append("")
    decisions = [
        d
        for d in sorted(fragments.decisions, key=lambda r: _entry_sort_key(r.fields.get("ID", r.path.stem)))
        if d.fields.get("Status") == "ACTIVE" and (last_digest is None or d.fields.get("Date", "") > last_digest)
    ]
    if not decisions:
        lines.append("None.")
    for record in decisions:
        fields = record.fields
        lines.append(f"- {fields.get('ID', record.path.stem)} ({fields.get('Date', '')}): {fields.get('Question', fields.get('Title', ''))}")
    lines.append("")
    lines.append("## Pending post-merge checks")
    lines.append("")
    checks: list[str] = []
    for record in sorted(fragments.status, key=_status_sort_key):
        for line in record.free_text.splitlines():
            stripped = line.strip()
            if stripped.startswith("Pending check:"):
                checks.append(f"- {record.fields.get('WP', '')}: {stripped[len('Pending check:'):].strip()}")
    if not checks:
        lines.append("None.")
    else:
        lines.extend(checks)
    return GENERATED_LINE + "\n".join(lines).rstrip("\n") + "\n"


def render_ledger(records: tuple[LedgerFragment, ...]) -> str:
    lines = ["# Outsourcing ledger", ""]
    header = "| WO | Date | Model | Model version | Attempts | Prompt tokens | Output tokens | Result | Seconds |"
    lines.append(header)
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for record in sorted(records, key=lambda r: _entry_sort_key(r.fields.get("WO", r.path.stem))):
        fields = record.fields
        cells = [
            fields.get("WO", record.path.stem),
            fields.get("Date", ""),
            fields.get("Model", ""),
            fields.get("Model version", ""),
            fields.get("Attempts", ""),
            fields.get("Prompt tokens", ""),
            fields.get("Output tokens", ""),
            fields.get("Result", ""),
            fields.get("Seconds", ""),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return GENERATED_LINE + "\n".join(lines).rstrip("\n") + "\n"


def render_all(fragments: Fragments, on_main: bool, last_digest: str | None = None) -> dict[Path, str]:
    """Render every generated table from fragments into {relative path: text}."""
    return {
        STATUS_PATH: render_status(fragments.status, on_main),
        BLOCKERS_PATH: render_blockers(fragments.blockers, on_main),
        DEBT_PATH: render_debt(fragments.debt, on_main),
        DECISIONS_PATH: render_decisions(fragments.decisions),
        OWNER_QUEUE_PATH: render_owner_queue(fragments, on_main, last_digest),
        LEDGER_PATH: render_ledger(fragments.ledger),
    }
