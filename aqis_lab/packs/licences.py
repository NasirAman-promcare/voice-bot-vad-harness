"""LICENCES.md of a pack: every source with its licence and the attribution it requires, and every clip's licence.

CAPABILITIES:
  CAP-PACK-007: licences_markdown() writes one section per source dataset used (licence name, ID and link for the dataset and for each licence of the files used, the dataset's attribution text, link to the material, changes made, per-file attributions such as each music track's title and artist, consent references, a notice for synthetic clips), a section for clips the lab generates, and a table mapping every clip to its category, licence, source files and consent reference; it holds no timestamps, so the same inputs give the same bytes; listed_clips() reads that table back for pack verify [tests: test_FR_0_4_07_lists_every_source_and_licence, test_FR_0_4_07_cc_by_attribution_has_required_elements, test_FR_0_4_07_music_tracks_attributed_individually, test_FR_0_4_07_owner_recordings_name_consent_ref, test_FR_0_4_07_synthetic_clips_attributed_under_apache_2, test_FR_0_4_07_generated_deterministically, test_FR_0_4_07_verify_fails_when_a_clip_is_missing]
INPUTS AND OUTPUTS: the PackSpec, the manifest dict, {clip_id: source RegistryRow values} and Datasets in; Markdown
  text out.
CONTRACTS: pack layout (docs/data/SMOKE_PACK.md); licence table of datasets.yaml.
INVARIANTS:
  - Every clip of the manifest appears in the table with exactly its manifest licence.
  - Every licence named is written with its full name and, where it has one, its link.
NOT IN SCOPE:
  - Deciding licences (data/registry/datasets.yaml); checking the file (aqis_lab/packs/verify.py).
CHANGE LOG:
  2026-09-27 WP-0.4 FR-0.4-07 created.
  2026-10-02 WP-0.8 DEBT-012 (WP-0.4-F05): "Changes made" is always the dataset's own changes text, which
    datasets.v1.json now requires; no default text.
"""
import re

CLIP_ROW_RE = re.compile(r"^\| `([a-z0-9-]+)` \| [^|]+ \| `([^`]+)` \|", re.M)
SYNTHETIC_NOTICE = ("These clips are synthetic speech, not recordings of a person. They must never be used to judge "
                    "or compare models.")


def _licence_text(datasets, licence_id):
    licence = datasets.licence(licence_id)
    link = f", {licence.url}" if licence.url else ""
    return f"{licence.name} (`{licence_id}`{link})"


def licences_markdown(spec, manifest, clip_sources, datasets):
    """The LICENCES.md text of a pack (see the module header)."""
    rows_by_dataset = {}
    for sources in clip_sources.values():
        for row in sources:
            rows_by_dataset.setdefault(row.dataset, {})[row.clip_id] = row
    uses = {}
    for clip in manifest["clips"]:
        for row in clip_sources[clip["clip_id"]]:
            uses.setdefault(row.dataset, set()).add(clip["clip_id"])
    lines = [f"# Licences: pack {spec.manifest_id} {spec.version}", "",
             "This file lists every source of the clips in this pack, its licence and the attribution its licence "
             "requires, and then the licence of every clip. It is generated by `python -m aqis_lab pack build` from "
             "the source registry (`data/registry/sources.csv`) and `data/registry/datasets.yaml`.", ""]
    for dataset_id in sorted(rows_by_dataset):
        dataset = datasets.datasets[dataset_id]
        rows = [rows_by_dataset[dataset_id][k] for k in sorted(rows_by_dataset[dataset_id])]
        lines += [f"## Source: {dataset_id} ({dataset['source']})", ""]
        if dataset["type"] == "download":
            lines.append(f"- Material: {dataset['homepage']} (archive {dataset['url']}, SHA-256 {dataset['sha256']})")
        else:
            homepage = f"{dataset['homepage']}; " if dataset["homepage"] else ""
            lines.append(f"- Material: {homepage}files in `{dataset['folder']}` of this repository")
        lines.append(f"- Licence of the dataset: {_licence_text(datasets, dataset['licence'])}")
        file_licences = sorted({row.licence for row in rows})
        lines.append("- Licences of the files used: " + "; ".join(_licence_text(datasets, lid) for lid in file_licences))
        lines.append(f"- Attribution: {dataset['attribution']}")
        lines.append(f"- Changes made: {dataset['changes']}")
        if any("synthetic" in row.tags for row in rows):
            lines.append(f"- Notice: {SYNTHETIC_NOTICE}")
        lines.append(f"- Clips of this pack using it: {len(uses[dataset_id])}")
        attributed = [row for row in rows if row.attribution]
        if attributed:
            lines += ["", "Per-file attribution:", ""]
            lines += [f"- `{row.clip_id}` (`{row.source_ref}`): {row.attribution}" for row in attributed]
        consented = [row for row in rows if row.consent_ref]
        if consented:
            lines += ["", "Consent references:", ""]
            lines += [f"- `{row.clip_id}`: consent `{row.consent_ref}`" for row in consented]
        lines.append("")
    generated = [c for c in manifest["clips"] if not clip_sources[c["clip_id"]]]
    if generated:
        lines += ["## Generated by the lab", "",
                  f"- {len(generated)} clip(s) of digital silence (every sample 0), made by the pack builder from no "
                  f"third-party material.",
                  f"- Licence: {_licence_text(datasets, datasets.generated_licence)}", ""]
    lines += ["## Clips", "", "| Clip | Category | Licence | Source files | Consent reference |",
              "| --- | --- | --- | --- | --- |"]
    for clip in manifest["clips"]:
        refs = ", ".join(f"`{row.source_ref}`" for row in clip_sources[clip["clip_id"]]) or "generated"
        consent = f"`{clip['consent_ref']}`" if clip["consent_ref"] else "none"
        lines.append(f"| `{clip['clip_id']}` | {clip['split']} | `{clip['licence']}` | {refs} | {consent} |")
    return "\n".join(lines) + "\n"


def listed_clips(text):
    """{clip_id: licence} from the clips table of a LICENCES.md text."""
    return {m.group(1): m.group(2) for m in CLIP_ROW_RE.finditer(text)}
