"""Acceptance tests for WO-1.0-04 (FR-1.0-04, FR-1.0-11): progress fragments, generated tables, lint, migration.

Written by Claude before the order was sent; the implementer must not edit this file. One test (or one
parametrised test) per must-catch behaviour of the order's section 8, plus positive controls. Modules are imported
inside the tests and the command line runs as a subprocess, so a missing package fails each test on its own.

Scratch repositories hold copies of the real legacy `STATUS.md`, `BLOCKERS.md` and `DEBT.md`. The strongest
check (B8, B11, must-catch 3 and 7) is the round trip: migrating them and rendering them again with no other
fragment gives each legacy file back byte for byte, below the generated-file line.
"""
