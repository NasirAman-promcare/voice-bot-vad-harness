def blocker(bid: str, wp: str, capability: str = "ACCESS", unblocks: str = "WP-2.1", raised: str = "2026-10-10",
            status: str = "OPEN", steps: int = 2) -> str:
    lines = [f"# {bid} — scratch blocker", f"Status: {status}", f"WP: {wp}"]
    if capability is not None:
        lines.append(f"Owner capability: {capability}")
    lines += [f"Raised: {raised}", "Session: https://claude.ai/code/session_scratch", f"Unblocks: {unblocks}",
              "Time needed: 5 minutes", "Loop: none", "", "What I need: a scratch thing.", "", "Why: a test.", "",
              "What I tried:", "- nothing", "", "Options:", "1. do it (recommended)", "", "Exact steps:"]
    lines += [f"{i}. Step {i}." for i in range(1, steps + 1)]
    lines += ["", "Meanwhile: other work.", "", "Owner answer:", ""]
    return "\n".join(lines)


def status(wp: str, state: str) -> str:
    return (f"WP: {wp}\nTitle: Scratch {wp}\nStatus: {state}\nTier: T2\nSize: S\nBranch: claude/wp-{wp[3]}-{wp[5]}-x\n"
            f"PR: none\nThread model: Sonnet high\nUpdated: 2026-10-10\n")


# ---------------------------------------------------------------- must-catch 3 and 7: migration round trip

def test_FR_1_0_04_mc03_mc07_migration_round_trip_is_byte_identical(repo, tmp_path):
    dry = cli(repo, "migrate", "--dry-run")
    assert dry.returncode == 0, dry.stdout + dry.stderr
    assert not (repo / "docs/progress/debt.d").exists()  # a dry run creates nothing
    proc = cli(repo, "migrate")
    assert proc.returncode == 0, proc.stdout + proc.stderr
    out = tmp_path / "out"
    proc = cli(repo, "build", "--on-main", "--out", str(out))
    assert proc.returncode == 0, proc.stdout + proc.stderr
    for rel in LEGACY:
        assert (out / rel).read_text(encoding="utf-8") == GENERATED_LINE + (ROOT / rel).read_text(encoding="utf-8"), rel


def legacy_ids() -> list[str]:
    text = "".join((ROOT / rel).read_text(encoding="utf-8") for rel in LEGACY[1:])
    return sorted(set(re.findall(r"^## (BLK-\d+)", text, re.M)) | set(re.findall(r"^\| (DEBT-\d+) \|", text, re.M)))


def test_FR_1_0_04_mc03_dry_run_lists_every_legacy_id(repo):
    proc = cli(repo, "migrate", "--dry-run")
    assert proc.returncode == 0
    ids = legacy_ids()
    assert len(ids) > 40
    missing = [i for i in ids if not re.search(rf"\b{re.escape(i)}\b", proc.stdout)]
    assert missing == []


def test_FR_1_0_04_mc03_every_legacy_id_has_a_fragment_holding_its_text(repo):
    assert cli(repo, "migrate").returncode == 0
    for rel, pattern, folder in (("docs/progress/BLOCKERS.md", r"^## (BLK-\d+)", "blockers.d"),
                                 ("docs/progress/DEBT.md", r"^\| (DEBT-\d+) \|", "debt.d")):
        text = (ROOT / rel).read_text(encoding="utf-8")
        for legacy_id in re.findall(pattern, text, re.M):
            fragment = (repo / "docs/progress" / folder / f"{legacy_id}.md").read_text(encoding="utf-8")
            assert re.search(r"^Legacy: yes\s*$", fragment, re.M), legacy_id
            if folder == "debt.d":
                row = next(line for line in text.splitlines() if line.startswith(f"| {legacy_id} |"))
                assert row in fragment.splitlines(), legacy_id
            else:
                entry = re.search(rf"^## {legacy_id} .*?(?=^## BLK-|\Z)", text, re.M | re.S).group(0).rstrip("\n")
                assert entry in fragment, legacy_id


