# ---------------------------------------------------------------- must-catch 4: owner queue order

def test_FR_1_0_04_mc04_owner_queue_orders_blockers_by_unmerged_wps(empty_repo, tmp_path):
    for wp, state in (("WP-2.1", "IN-BUILD"), ("WP-2.2", "NOT-STARTED"), ("WP-2.3", "MERGED")):
        write(empty_repo, f"docs/progress/status.d/{wp}.md", status(wp, state))
    write(empty_repo, "docs/progress/blockers.d/BLK-2.1-01.md",
          blocker("BLK-2.1-01", "WP-2.1", unblocks="WP-2.1", raised="2026-10-01"))
    write(empty_repo, "docs/progress/blockers.d/BLK-2.1-02.md",
          blocker("BLK-2.1-02", "WP-2.1", unblocks="WP-2.1, WP-2.2, WP-2.3", raised="2026-10-05"))
    write(empty_repo, "docs/progress/blockers.d/BLK-2.3-01.md",
          blocker("BLK-2.3-01", "WP-2.3", unblocks="WP-2.3", raised="2026-09-01"))
    write(empty_repo, "docs/progress/blockers.d/BLK-2.2-01.md",
          blocker("BLK-2.2-01", "WP-2.2", unblocks="WP-2.1", raised="2026-09-20"))
    write(empty_repo, "docs/progress/blockers.d/BLK-2.2-02.md",
          blocker("BLK-2.2-02", "WP-2.2", unblocks="WP-2.2", raised="2026-09-25", status="RESOLVED"))
    out = tmp_path / "out"
    proc = cli(empty_repo, "build", "--on-main", "--out", str(out))
    assert proc.returncode == 0, proc.stdout + proc.stderr
    queue = (out / "docs/progress/OWNER_QUEUE.md").read_text(encoding="utf-8")
    order = [m.group(0) for m in re.finditer(r"BLK-2\.\d-0\d", queue)]
    firsts = list(dict.fromkeys(order))
    # 2 unmerged WPs first; then 1 unmerged, oldest first; then 0 unmerged; resolved blockers are not queued.
    assert firsts[:4] == ["BLK-2.1-02", "BLK-2.2-01", "BLK-2.1-01", "BLK-2.3-01"]
    assert "BLK-2.2-02" not in queue
    assert "Step 1." in queue and "ACCESS" in queue


# ---------------------------------------------------------------- must-catch 5: byte-identical rendering

def test_FR_1_0_04_mc05_rendering_is_byte_identical_across_runs_and_file_order(repo, tmp_path):
    assert cli(repo, "migrate").returncode == 0
    names = ("BLK-2.1-01", "BLK-2.1-02", "BLK-2.2-01")
    for bid in reversed(names):
        write(repo, f"docs/progress/blockers.d/{bid}.md", blocker(bid, f"WP-{bid[4:7]}"))
    first, second = tmp_path / "a", tmp_path / "b"
    assert cli(repo, "build", "--out", str(first)).returncode == 0
    for bid in names:  # rewrite in the other order: same content, new file order and modification times
        path = repo / f"docs/progress/blockers.d/{bid}.md"
        text = path.read_text(encoding="utf-8")
        path.unlink()
        write(repo, f"docs/progress/blockers.d/{bid}.md", text)
    assert cli(repo, "build", "--out", str(second)).returncode == 0
    files = sorted(p.relative_to(first) for p in first.rglob("*.md"))
    assert {"docs/progress/OWNER_QUEUE.md", "docs/progress/DECISIONS.md", "docs/outsourcing/LEDGER.md"} <= {
        p.as_posix() for p in files}
    for rel in files:
        assert (first / rel).read_bytes() == (second / rel).read_bytes(), rel
        assert (first / rel).read_text(encoding="utf-8").startswith(GENERATED_LINE), rel


