"""WP-1.2: the strict config loader for config/aqis_lab/s2.yaml and the integrity of the s2-live lock."""
import copy
import re
import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

from aqis_lab.live import config as live_config

REPO = Path(__file__).resolve().parents[2]
S2_YAML = REPO / "config" / "aqis_lab" / "s2.yaml"
LOCK_DIR = REPO / "requirements" / "aqis_lab"


def load_raw():
    return yaml.safe_load(S2_YAML.read_text(encoding="utf-8"))


def write(tmp_path, data):
    path = tmp_path / "s2.yaml"
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    return path


def test_s2_the_committed_config_loads_and_hashes_its_content():
    cfg = live_config.load_config(S2_YAML)
    assert cfg.seed == 20261026 and cfg.schema == "s2-v1"
    assert {"silero_v5", "silero_v4", "firered_vad", "webrtc_vad", "ten_vad"} <= set(cfg.vad)
    assert cfg.turn_end["fixed_thresholds_ms"] == [300, 500, 700, 1000]
    assert cfg.stt_streaming["chunk_sizes_ms"] == [160, 320, 640] and cfg.stt_streaming["target_rtf_max"] == 0.35
    assert len(cfg.hash) == 64 and cfg.hash == live_config.load_config(S2_YAML).hash


def test_s2_ten_vad_runs_only_where_it_has_a_build():
    cfg = live_config.load_config(S2_YAML)
    assert cfg.vad_supported("ten_vad", "x86_64") and not cfg.vad_supported("ten_vad", "aarch64")
    assert cfg.vad_supported("silero_v5", "aarch64")


def test_s2_config_hash_changes_when_a_value_changes(tmp_path):
    data = load_raw()
    data["seed"] = 1
    assert live_config.load_config(write(tmp_path, data)).hash != live_config.load_config(S2_YAML).hash


@pytest.mark.parametrize("mutate,message", [
    (lambda d: d.update(surprise=1), "surprise"),
    (lambda d: d.update(schema="s2-v2"), "schema"),
    (lambda d: d.pop("seed"), "seed"),
    (lambda d: d["vad"].update(mystery_vad={"hf": "x/y"}), "mystery_vad"),
    (lambda d: d["vad"]["webrtc_vad"].update(modes=[1, 7]), "mode"),
    (lambda d: d["vad"]["silero_v5"].update(threshold=1.5), "threshold"),
    (lambda d: d["turn_end"].update(fixed_thresholds_ms=[]), "fixed_thresholds_ms"),
    (lambda d: d["turn_end"].update(fixed_thresholds_ms=[300, -5]), "fixed_thresholds_ms"),
    (lambda d: d["stt_streaming"].update(chunk_sizes_ms=[160, 0]), "chunk_sizes_ms"),
    (lambda d: d["stt_streaming"].update(target_rtf_max=0), "target_rtf_max"),
    (lambda d: d["emotion"].update(mystery={"hf": "a/b"}), "mystery"),
    (lambda d: d["conditions"].update(vad=["phone", "studio"]), "studio"),
    (lambda d: d["conditions"].pop("turn"), "turn"),
    (lambda d: d["scoring"].update(collars_ms=[-1]), "collars_ms"),
])
def test_s2_config_rejects_what_it_does_not_understand(tmp_path, mutate, message):
    data = copy.deepcopy(load_raw())
    mutate(data)
    with pytest.raises(live_config.ConfigError, match=message):
        live_config.load_config(write(tmp_path, data))


def test_s2_missing_config_file_is_an_error(tmp_path):
    with pytest.raises(live_config.ConfigError, match="s2.yaml"):
        live_config.load_config(tmp_path / "s2.yaml")


# ---- the lock -------------------------------------------------------------------------------------------------------
def lock_text():
    return (LOCK_DIR / "s2-live.txt").read_text(encoding="utf-8")


def test_s2_live_lock_names_its_command_and_both_architectures():
    header = lock_text().splitlines()[:3]
    assert header[0].startswith("# This file was autogenerated by uv") and "uv pip compile requirements/aqis_lab/s2-live.in" in header[1]
    assert "--universal" in header[1] and "--python-version 3.13" in header[1] and "--generate-hashes" in header[1]


def test_s2_live_lock_pins_every_package_with_hashes():
    text = lock_text()
    pins = re.findall(r"^([A-Za-z0-9_.\-\[\]]+)==([^\s;\\]+)", text, re.M)
    assert len(pins) > 20
    blocks = re.split(r"^(?=[A-Za-z0-9_.\-\[\]]+==)", text, flags=re.M)[1:]
    for block in blocks:
        assert "--hash=sha256:" in block, block.splitlines()[0]


def test_s2_live_lock_holds_the_packages_the_stages_need():
    text = lock_text()
    for name in ("onnxruntime", "numpy", "pyarrow", "pyyaml", "soundfile", "huggingface-hub", "transformers", "torch", "funasr",
                 "onnx-asr", "webrtcvad-wheels", "fireredvad", "ten-vad"):
        assert re.search(rf"^{re.escape(name)}==", text, re.M | re.I), name


def test_s2_live_lock_agrees_with_the_phase_0_pins_it_shares():
    phase0 = dict(re.findall(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)", (LOCK_DIR / "phase0.txt").read_text(encoding="utf-8"), re.M))
    s2 = dict(re.findall(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)", lock_text(), re.M))
    for name in ("numpy", "pyarrow", "pyyaml", "soundfile", "whisper-normalizer"):
        if name in s2:
            assert s2[name] == phase0[name], name
    assert (LOCK_DIR / "s2-live.in").is_file()


SOURCE_BUILDS = ("textgrid", "antlr4-python3-runtime", "jieba", "oss2", "crcmod")      # no wheel exists; they build from source


@pytest.mark.network
@pytest.mark.parametrize("platform", ["aarch64-manylinux_2_28", "x86_64-manylinux_2_28"])
def test_s2_live_lock_resolves_to_installable_builds_on_both_machines(platform):
    """The Oracle VM is aarch64 and Colab is x86_64: every pin must have a wheel there, except the five named source builds."""
    uv = shutil.which("uv")
    assert uv, "uv is needed to resolve the lock"
    command = [uv, "pip", "install", "--dry-run", "--require-hashes", "--no-deps", "--only-binary", ":all:",
               *[arg for name in SOURCE_BUILDS for arg in ("--no-binary", name)], "--python-platform", platform,
               "--python-version", "3.13", "-r", str(LOCK_DIR / "s2-live.txt")]
    proc = subprocess.run(command, capture_output=True, text=True, timeout=900)
    assert proc.returncode == 0, proc.stderr[-2000:]
