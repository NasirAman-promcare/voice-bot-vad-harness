def header_capabilities(root: Path) -> dict[str, tuple[str, set[str]]]:
    """Capability IDs named in the CAPABILITIES section of source module docstrings, read independently."""
    found: dict[str, tuple[str, set[str]]] = {}
    for tree in ("aqis_lab", "tools", "kit-staging"):
        for path in sorted((root / tree).rglob("*.py")) if (root / tree).is_dir() else []:
            doc = ast.get_docstring(ast.parse(path.read_bytes()), clean=False) or ""
            if "CAPABILITIES:" not in doc:
                continue
            body = []
            for line in doc.split("CAPABILITIES:", 1)[1].splitlines()[1:]:
                if re.match(r"^[A-Z][A-Z ]+:", line):
                    break
                body.append(line)
            for m in re.finditer(r"^\s+(CAP-[A-Z0-9-]+):(.*?)(?=^\s+CAP-|\Z)", "\n".join(body), re.S | re.M):
                tests = re.search(r"\[tests:(.*?)\]", m.group(2), re.S)
                names = {t.strip().strip("`") for t in (tests.group(1) if tests else "").split(",") if t.strip()}
                found[m.group(1)] = (path.relative_to(root).as_posix(), names)
    return found


def test_FR_1_0_03_adopting_the_real_registry_accounts_for_every_legacy_row(tmp_path: Path) -> None:
    copy = tmp_path / "real"
    copy.mkdir()
    trees = [t for t in ("aqis_lab", "tools", "kit-staging", "tests/aqis_lab", "docs/capabilities")
             if subprocess.run(["git", "cat-file", "-e", f"HEAD:{t}"], cwd=ROOT, capture_output=True).returncode == 0]
    archive = subprocess.run(["git", "archive", "--format=tar", "HEAD", *trees], cwd=ROOT, check=True,
                             capture_output=True).stdout
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        tar.extractall(copy, filter="data")
    git(copy, "init", "-q")
    commit(copy, "copy of HEAD")

    gate = importlib.import_module("tools.audit.gate")
    legacy = registry_rows(read(copy, "docs/capabilities/REGISTRY.md"))
    headers = header_capabilities(copy)
    proc = cli(copy, "build", "--adopt-registry")
    assert proc.returncode == 0, (proc.stdout + proc.stderr)[-3000:]

    text = read(copy, "docs/capabilities/REGISTRY.md")
    header_line = next(line for line in text.splitlines() if line.startswith("| Capability ID"))
    assert tuple(gate._cells(header_line)) == gate.REGISTRY_COLUMNS
    rows = registry_rows(text)
    assert set(legacy) <= set(rows), sorted(set(legacy) - set(rows))
    assert set(headers) <= set(rows), sorted(set(headers) - set(rows))
    non_code = {cap for cap in legacy if cap not in headers}
    records = {p.stem for p in (copy / "docs/capabilities/records.d").glob("*.md")}
    assert records == non_code
    for cap in non_code:
        assert rows[cap] == legacy[cap], cap
    for cap, (module, tests) in headers.items():
        cells = rows[cap]
        assert len(cells) == 7 and cells[1].strip("` ") == module and cells[6] == "ACTIVE", cap
        assert {t.strip().strip("`") for t in cells[4].split(",") if t.strip()} == tests, cap
