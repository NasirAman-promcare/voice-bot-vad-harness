def changed_on_branch(repo: Path, rel: str, text: str | None) -> list[str]:
    git(repo, "checkout", "-qb", "work")
    if text is None:
        (repo / rel).unlink()
    else:
        write(repo, rel, text)
    commit(repo, "change")
    proc = cli(repo, "impact", "--base", "main")
    assert proc.returncode == 0, proc.stdout + proc.stderr
    return proc.stdout.splitlines()


