def section(text: str, heading: str) -> str:
    """The lines after the `## ` heading whose text is exactly `heading`, up to the next `## ` heading."""
    out, inside, found = [], False, False
    for line in text.splitlines():
        if line.startswith("## "):
            if inside:
                break
            inside = found = line[3:].strip() == heading
            continue
        if inside:
            out.append(line)
    assert found, f"no section headed {heading!r} in:\n{text}"
    return "\n".join(out)


def line_of(text: str, needle: str) -> int:
    return next(n for n, line in enumerate(text.splitlines(), start=1) if needle in line)


def registry_rows(text: str) -> dict[str, list[str]]:
    gate = importlib.import_module("tools.audit.gate")
    rows, problems = gate.parse_registry(text)
    assert problems == [], problems
    return {gate._unquote(cells[0]): cells for _, cells in rows}


