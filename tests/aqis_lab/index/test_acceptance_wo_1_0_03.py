def git(repo: Path, *args: str) -> str:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update({"GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1", "GIT_AUTHOR_NAME": "AQIS Fixture",
                "GIT_AUTHOR_EMAIL": "fixture@example.invalid", "GIT_COMMITTER_NAME": "AQIS Fixture",
                "GIT_COMMITTER_EMAIL": "fixture@example.invalid"})
    proc = subprocess.run(["git", "-c", "init.defaultBranch=main", *args], cwd=repo, check=True,
                          capture_output=True, text=True, env=env, timeout=120)
    return proc.stdout


def cli(repo: Path, *args: str, env_extra: dict | None = None) -> subprocess.CompletedProcess:
    env = dict(os.environ, PYTHONPATH=str(ROOT))
    env.update(env_extra or {})
    return subprocess.run([sys.executable, "-P", "-m", "tools.index", *args], cwd=repo, capture_output=True,
                          text=True, env=env, timeout=300)


def write(repo: Path, rel: str, text: str) -> None:
    (repo / rel).parent.mkdir(parents=True, exist_ok=True)
    (repo / rel).write_text(text, encoding="utf-8")


def header(purpose: str, caps: list[str], log: str) -> str:
    lines = [f'"""{purpose}', "", "CAPABILITIES:"]
    lines += [f"  {cap}" for cap in caps] or ["  none."]
    lines += ["INPUTS AND OUTPUTS: scratch values in, scratch values out.", "CONTRACTS: none.", "INVARIANTS:",
              "  - Scratch only.", "NOT IN SCOPE:", "  - Anything real.", "CHANGE LOG:", f"  {log}", '"""']
    return "\n".join(lines) + "\n"


