def make_repo(root: Path, order: list[str] | None = None) -> Path:
    for rel in order or list(FILES):
        write(root, rel, FILES[rel])
    git(root, "init", "-q")
    git(root, "add", "-A")
    git(root, "commit", "-qm", "base")
    return root


