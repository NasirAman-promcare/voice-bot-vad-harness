def test_s3_config_rejects_what_it_does_not_understand(tmp_path, mutate, message):
    data = copy.deepcopy(load_raw())
    mutate(data)
    with pytest.raises(cascade_config.ConfigError, match=message):
        cascade_config.load_config(write(tmp_path, data))


def test_s3_missing_config_file_is_an_error(tmp_path):
    with pytest.raises(cascade_config.ConfigError, match="s3.yaml"):
        cascade_config.load_config(tmp_path / "s3.yaml")


def test_s3_condition_mix_weights_sum_to_one():
    mix = cascade_config.load_config(S3_YAML).train["condition_mix"]
