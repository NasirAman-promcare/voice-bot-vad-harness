def test_s3_config_rejects_what_it_does_not_understand(tmp_path, mutate, message):
    data = copy.deepcopy(load_raw())
    mutate(data)
    with pytest.raises(cascade_config.ConfigError, match=message):
        cascade_config.load_config(write(tmp_path, data))


def test_s3_missing_config_file_is_an_error(tmp_path):
    with pytest.raises(cascade_config.ConfigError, match="s3.yaml"):
        cascade_config.load_config(tmp_path / "s3.yaml")


def test_s3_condition_mix_weights_sum_to_one():
    mix = cascade_config.load_config(S3_YAML).train["condition_mix"]
    assert sum(mix.values()) == pytest.approx(1.0)


# ---- the locks ----------------------------------------------------------------------------------------------------
def lock_text(name):
    return (LOCK_DIR / name).read_text(encoding="utf-8")


def pins(text):
    return dict(re.findall(r"^([A-Za-z0-9_.\-]+)==([^\s;\\]+)", text, re.M))


@pytest.mark.parametrize("name", ["s3-cascade", "s3-train"])
def test_s3_locks_name_their_command_and_hash_every_pin(name):
    text = lock_text(f"{name}.txt")
    header = text.splitlines()[:3]
    assert header[0].startswith("# This file was autogenerated by uv") and f"uv pip compile requirements/aqis_lab/{name}.in" in header[1]
    assert "--generate-hashes" in header[1] and "--python-version 3.13" in header[1]
    blocks = re.split(r"^(?=[A-Za-z0-9_.\-\[\]]+==)", text, flags=re.M)[1:]
    assert len(blocks) > 10
    for block in blocks:
        assert "--hash=sha256:" in block, block.splitlines()[0]
    assert (LOCK_DIR / f"{name}.in").is_file()


def test_s3_cascade_lock_holds_what_the_cpu_stages_need():
    text = pins(lock_text("s3-cascade.txt"))
    for name in ("numpy", "pyarrow", "pyyaml", "soundfile", "onnxruntime", "matplotlib", "huggingface-hub"):
        assert name in text, name


def test_s3_train_lock_holds_the_lora_stack_on_the_qwen_pins_of_sprint_1():
    train, qwen = pins(lock_text("s3-train.txt")), pins(lock_text("s1-qwen.txt"))
    for name in ("peft", "bitsandbytes", "qwen-asr", "torch", "transformers", "accelerate"):
        assert name in train, name
    for name in ("qwen-asr", "torch", "transformers", "accelerate", "numpy"):
        assert train[name] == qwen[name], f"{name}: Sprint 1 ran Qwen3-ASR on {qwen[name]}"


def test_s3_locks_agree_with_the_phase_0_pins_they_share():
    phase0 = pins(lock_text("phase0.txt"))
    for name in ("s3-cascade.txt", "s3-train.txt"):
        got = pins(lock_text(name))
        for package in ("numpy", "pyarrow", "pyyaml", "soundfile"):
            if package in got:
                assert got[package] == phase0[package], (name, package)
