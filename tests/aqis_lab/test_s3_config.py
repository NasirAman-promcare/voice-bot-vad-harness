"""WP-1.3: the strict config loader for config/aqis_lab/s3.yaml and the integrity of the s3 locks."""
import copy
import re
from pathlib import Path

import pytest
import yaml

from aqis_lab.cascade import config as cascade_config

REPO = Path(__file__).resolve().parents[2]
S3_YAML = REPO / "config" / "aqis_lab" / "s3.yaml"
LOCK_DIR = REPO / "requirements" / "aqis_lab"


def load_raw():
    return yaml.safe_load(S3_YAML.read_text(encoding="utf-8"))


def write(tmp_path, data):
    path = tmp_path / "s3.yaml"
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    return path


def test_s3_the_committed_config_loads_and_hashes_its_content():
    cfg = cascade_config.load_config(S3_YAML)
    assert cfg.schema == "s3-v1" and cfg.seed == 20261102
    assert cfg.cascade["stage1"] == "parakeet-tdt-0.6b-v2" and cfg.cascade["heavy"] == ["qwen3-asr-1.7b", "cohere-transcribe-2b"]
    assert (cfg.cascade["target_wer_max"], cfg.cascade["escalation_max"]) == (0.12, 0.35)
    assert (cfg.train["lora"]["r"], cfg.train["lora"]["alpha"]) == (16, 32)
    assert cfg.eval["drug_recall_min"] == 0.75 and cfg.eval["us_conv_wer_increase_max"] == 0.005
    assert len(cfg.hash) == 64 and cfg.hash == cascade_config.load_config(S3_YAML).hash


def test_s3_config_hash_changes_when_a_value_changes(tmp_path):
    data = load_raw()
    data["seed"] = 1
    assert cascade_config.load_config(write(tmp_path, data)).hash != cascade_config.load_config(S3_YAML).hash


