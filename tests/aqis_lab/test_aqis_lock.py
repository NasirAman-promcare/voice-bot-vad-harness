"""FR-0.0-03: requirements/aqis_lab/phase0.txt pins every package with hashes and is generated from phase0.in."""
import importlib.metadata as md
import re
import shutil
import subprocess
import sys

import pytest
from packaging.markers import Marker

from aqis_testutil import LOCK, LOCK_IN, ROOT, normalise, parse_lock, pip_venv, probe_python_major_minor


def lock_header_command():
    lines = LOCK.read_text(encoding="utf-8").splitlines()
    assert lines[0].startswith("# This file was autogenerated by uv via the following command:"), lines[0]
    return lines[1].lstrip("#").strip()


def in_file_requirements():
    names = []
    for raw in LOCK_IN.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            names.append(normalise(re.split(r"[<>=!~;\[ ]", line, maxsplit=1)[0]))
    return names


def test_FR_0_0_03_every_pin_has_hashes():
    entries = parse_lock()
    assert entries, "phase0.txt has no requirements"
    for name, entry in entries.items():
        assert entry["hashes"], f"{name} has no --hash"
        for algo, digest in entry["hashes"]:
            assert algo == "sha256", f"{name} uses {algo}"
            assert len(digest) == 64, f"{name} has a malformed sha256"


def test_FR_0_0_03_lock_generated_from_in_file():
    entries = parse_lock()
    direct = in_file_requirements()
    for required in ("pytest", "jsonschema"):
        assert required in direct, f"{required} missing from phase0.in"
    for name in direct:
        assert name in entries, f"{name} from phase0.in is not pinned in phase0.txt"
    # uv annotates each pin with what pulled it in; direct pins name phase0.in itself.
    blocks = {}
    for block in re.split(r"\n(?=[A-Za-z0-9])", LOCK.read_text(encoding="utf-8")):
        head = block.split("==", 1)[0].strip()
        if head and not head.startswith("#"):
            blocks[normalise(head)] = block
    assert set(blocks) == set(entries)
    for name, block in blocks.items():
        assert "# via" in block, f"no provenance annotation for {name}"
        from_in = "-r requirements/aqis_lab/phase0.in" in block
        assert from_in == (name in direct), f"{name}: provenance does not match phase0.in"


def test_FR_0_0_03_regeneration_command_documented():
    command = lock_header_command()
    probe = probe_python_major_minor()
    assert command.startswith("uv pip compile requirements/aqis_lab/phase0.in"), command
    for part in ("--universal", f"--python-version {probe}", "--generate-hashes",
                 "--output-file requirements/aqis_lab/phase0.txt"):
        assert part in command, f"{part!r} missing from the recorded command: {command}"
    assert command in LOCK_IN.read_text(encoding="utf-8"), "phase0.in does not document the regeneration command"


def test_FR_0_0_03_environment_matches_lock():
    entries = parse_lock()
    applicable = {name: e for name, e in entries.items() if not e["marker"] or Marker(e["marker"]).evaluate()}
    installed = {normalise(d.metadata["Name"]): d.version for d in md.distributions()}
    for name, entry in applicable.items():
        assert installed.get(name) == entry["version"], f"{name}: installed {installed.get(name)}, lock {entry['version']}"
    extra = sorted(set(installed) - set(applicable))
    assert not extra, f"packages installed but not in the lock: {extra}"


@pytest.mark.slow
@pytest.mark.network
def test_FR_0_0_03_regeneration_is_reproducible(tmp_path):
    out = tmp_path / "phase0.txt"
    shutil.copyfile(LOCK, out)
    command = lock_header_command().split()
    command[command.index("--output-file") + 1] = str(out)
    command.extend(["--custom-compile-command", lock_header_command()])
    proc = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, timeout=600)
    assert proc.returncode == 0, proc.stderr
    assert out.read_text(encoding="utf-8") == LOCK.read_text(encoding="utf-8")


@pytest.mark.slow
@pytest.mark.network
def test_FR_0_0_03_lock_installable_with_plain_pip(tmp_path):
    venv = tmp_path / "pipvenv"
    pip_venv(venv)
    pip = [str(venv / "bin" / "python"), "-m", "pip"]
    proc = subprocess.run([*pip, "install", "--require-hashes", "--no-input", "-r", str(LOCK)],
                          capture_output=True, text=True, timeout=900)
    assert proc.returncode == 0, proc.stdout[-2000:] + proc.stderr[-2000:]
    check = subprocess.run([str(venv / "bin" / "python"), "-c",
                            "import importlib.metadata as m; print(m.version('pytest'), m.version('jsonschema'))"],
                           capture_output=True, text=True, timeout=120)
    assert check.stdout.split() == [parse_lock()["pytest"]["version"], parse_lock()["jsonschema"]["version"]]
