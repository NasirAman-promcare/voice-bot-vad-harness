"""WP-0.4 FR-0.4-07: LICENCES.md lists every source, its licence and the attribution it requires (licences.py)."""
import re
import shutil

import pytest

from aqis_packs_testutil import RFM_TEMPLATE, build_test_pack, make_world, read_json, spec_dict
from aqis_lab.packs.licences import listed_clips
from aqis_lab.packs.verify import verify_pack
from aqis_lab.registry.datasets import load_datasets

# What CC BY 3.0 and 4.0 (legal code, section 3(a)(1) of 4.0; section 4(b) of 3.0) require when material is
# shared, written out here from the licence texts: identify the creator and others to be attributed, keep a
# notice that refers to the licence with its text or URI, give the URI of the material, and say whether and how
# it was changed.
CC_BY_ELEMENTS = ("creator attribution", "licence notice with link", "link to the material", "changes made")


@pytest.fixture(scope="module")
def built(tmp_path_factory):
    base = tmp_path_factory.mktemp("licences")
    world = make_world(base / "world")
    out = base / "pack"
    build_test_pack(world, out)
    return world, out


def _sections(text):
    parts = re.split(r"^## ", text, flags=re.M)
    return {p.split("\n", 1)[0]: p for p in parts[1:]}


def test_FR_0_4_07_lists_every_source_and_licence(built):
    world, out = built
    text = (out / "LICENCES.md").read_text(encoding="utf-8")
    manifest = read_json(out / "manifest.json")
    listed = listed_clips(text)
    assert listed == {c["clip_id"]: c["licence"] for c in manifest["clips"]}
    datasets = load_datasets(world.datasets_path)
    sections = _sections(text)
    for dataset_id in ("librispeech-test-clean", "librispeech-test-other", "musan", "tts-smoke"):
        (section,) = [s for title, s in sections.items() if title.startswith(f"Source: {dataset_id} ")]
        dataset = datasets.datasets[dataset_id]
        assert dataset["attribution"] in section
        licence = datasets.licence(dataset["licence"])
        assert licence.name in section and licence.url in section
    assert "Generated by the lab" in sections and "CC0-1.0" in sections["Generated by the lab"]
    every_licence = {part for c in manifest["clips"] for part in c["licence"].split(" AND ")}
    for licence_id in every_licence:
        assert datasets.licence(licence_id).name in text, licence_id


def test_FR_0_4_07_cc_by_attribution_has_required_elements(built):
    world, out = built
    text = (out / "LICENCES.md").read_text(encoding="utf-8")
    datasets = load_datasets(world.datasets_path)
    for title, section in _sections(text).items():
        if not title.startswith("Source: "):
            continue
        dataset = datasets.datasets[title.split()[1]]
        uses_cc_by = any(datasets.licence(lid).attribution_required and lid.startswith("CC-BY")
                         for lid in re.findall(r"`(CC-BY-[0-9.]+)`", section))
        if not uses_cc_by:
            continue
        found = {
            "creator attribution": f"- Attribution: {dataset['attribution']}" in section,
            "licence notice with link": all(datasets.licence(lid).url in section
                                            for lid in re.findall(r"`(CC-BY-[0-9.]+)`", section)),
            "link to the material": f"- Material: {dataset['homepage']}" in section,
            "changes made": re.search(r"^- Changes made: \S", section, flags=re.M) is not None,
        }
        assert set(found) == set(CC_BY_ELEMENTS) and all(found.values()), (title, found)


def test_FR_0_4_07_music_tracks_attributed_individually(built):
    world, out = built
    text = (out / "LICENCES.md").read_text(encoding="utf-8")
    manifest = read_json(out / "manifest.json")
    music = [c for c in manifest["clips"] if "music" in c["tags"]]
    assert music
    for clip in music:
        (source_id,) = clip["recipe"]["source_clip_ids"]
        number = int(source_id.rsplit("-", 1)[1])
        line = RFM_TEMPLATE.format(title=f"Track {number}", artist="Kevin MacLeod")
        assert f"- `{source_id}` (`{clip['source_ref']}`): {line}" in text


def test_FR_0_4_07_owner_recordings_name_consent_ref(tmp_path):
    world = make_world(tmp_path / "w", owner=True)
    owner = {"name": "owner", "count": 2, "tags": ["owner", "speech"], "parts": [
        {"kind": "take", "count": 2, "from": {"source": "owner", "split": "owner"}}]}
    spec = spec_dict()
    spec["licence_policy"]["allow_non_commercial"] = True        # the owner licence forbids redistribution
    result = build_test_pack(world, tmp_path / "pack", categories=spec["categories"] + [owner],
                             licence_policy=spec["licence_policy"])
    owners = [c for c in result.manifest["clips"] if c["source"] == "owner"]
    assert len(owners) == 2 and all(c["consent_ref"] == "data/owner_smoke/CONSENT.md" for c in owners)
    text = (tmp_path / "pack" / "LICENCES.md").read_text(encoding="utf-8")
    for clip in owners:
        assert f"- `{clip['clip_id']}`: consent `data/owner_smoke/CONSENT.md`" in text
        assert f"| `{clip['clip_id']}` | owner | `LicenseRef-AQIS-owner-consent` |" in text
    assert verify_pack(tmp_path / "pack").ok


def test_FR_0_4_07_synthetic_clips_attributed_under_apache_2(built):
    _, out = built
    sections = _sections((out / "LICENCES.md").read_text(encoding="utf-8"))
    (section,) = [s for title, s in sections.items() if title.startswith("Source: tts-smoke ")]
    assert "Apache License 2.0 (`Apache-2.0`, https://www.apache.org/licenses/LICENSE-2.0)" in section
    assert "hexgrad/Kokoro-82M" in section and "https://huggingface.co/hexgrad/Kokoro-82M" in section
    assert "synthetic speech, not recordings of a person" in section
    assert "never be used to judge or compare models" in section
    assert "recording" not in section.replace("not recordings of a person", "")


def test_FR_0_4_07_generated_deterministically(tmp_path, built):
    world, out = built
    again = tmp_path / "again"
    build_test_pack(world, again)
    assert (again / "LICENCES.md").read_bytes() == (out / "LICENCES.md").read_bytes()
    text = (out / "LICENCES.md").read_text(encoding="utf-8")
    assert not re.search(r"\d{2}:\d{2}:\d{2}", text) and "2026-09-27" not in text


def test_FR_0_4_07_verify_fails_when_a_clip_is_missing(tmp_path, built):
    _, out = built
    pack = tmp_path / "pack"
    shutil.copytree(out, pack)
    manifest = read_json(pack / "manifest.json")
    victim = manifest["clips"][3]["clip_id"]
    text = (pack / "LICENCES.md").read_text(encoding="utf-8")
    (pack / "LICENCES.md").write_text("\n".join(l for l in text.splitlines() if not l.startswith(f"| `{victim}`")) + "\n")
    assert verify_pack(pack).problems == [f"LICENCES.md: does not list clip {victim} with licence "
                                          f"{manifest['clips'][3]['licence']}"]
    (pack / "LICENCES.md").write_text(text.replace(f"| `{victim}` | {manifest['clips'][3]['split']} | `",
                                                   f"| `{victim}` | {manifest['clips'][3]['split']} | `X-"))
    assert len(verify_pack(pack).problems) == 1
